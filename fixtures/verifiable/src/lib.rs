//! 一个带已知缺陷的示例库，供 `proofforge verify` 手动验证使用。
//!
//! 它存在的理由是：**行为验证需要一条能被复现的缺陷**。`over-engineered`
//! 植入的是静态可见的结构问题（过度设计、重复代码），`verify` 对它们无话可说
//! ——它回答的是「程序在某个输入下做了什么」，不是「代码长什么样」。
//!
//! 这里植入两条：
//!
//! 1. [`parse`] 对非正输入会 panic。这是一个**可复现**的缺陷：性质
//!    `output < usize::MAX` 配上输入域 `[-20, 20]` 必然违反，反例可被缩减到 0。
//! 2. [`double`] 是干净的。它守护的是「未观察到违反」这条路径——如果连它也
//!    报违反，说明验证机制本身坏了。
//!
//! 这个文件同时是 ProofForge CLI 测试的夹具，修改前请先确认
//! `crates/pf-cli/tests/cli.rs` 中的断言仍然成立。

/// 把整数转成 `usize`。
///
/// # 已知缺陷
///
/// `value <= 0` 时 `(value - 1)` 为负，`try_into()` 失败并 panic。这就是夹具
/// 要复现的行为，不要「顺手修好」它。
pub fn parse(value: i64) -> usize {
    (value - 1).try_into().unwrap()
}

/// 把输入翻倍。
///
/// 这个函数是干净的：任意整数翻倍后仍然是偶数。
pub fn double(value: i64) -> i64 {
    value * 2
}

/// 两数相加。
///
/// 它是**双参数**的，存在的唯一理由是给 `relations.json` 里的元组域蜕变关系
/// 提供一个形状匹配的目标：元组域会按字段展开成多个实参，单参数的 `double` 与
/// `parse` 都接不住。功能本身没有可验证的趣味。
pub fn add(left: i64, right: i64) -> i64 {
    left + right
}
